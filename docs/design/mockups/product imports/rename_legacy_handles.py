#!/usr/bin/env python3
"""Rename the 96 legacy Calder products to the PN-derived handle scheme.

WHY A SCRIPT: Shopify's CSV import keys on Handle — changing the Handle column
in a CSV creates a NEW product (duplicate) instead of renaming. Renames must
go through the Admin API (or the admin UI). This script applies
docs/architecture/calder_handle_migration.csv (generated by
build_design_registry.py) one product at a time.

Target scheme (derived 1:1 from the part_number — handle = f(SKU)):
    {design-lower}-{pcd}-cb{bore*10}-et{offset:02d}-{lip gb|pl}-{bolt ch|bk}
    e.g. calder-clb-07-5x120-p32-72-6mm-gloss-black-lip-black-bolts-wheels
         -> clb07-5x120-cb726-et32-gb-bk

Universal calder-*-wheel design products are NOT touched (customer-facing).

Usage:
    # dry run (default) - prints the rename table, changes nothing
    python3 rename_legacy_handles.py

    # apply
    export SHOPIFY_SHOP='wvpnpr-t7'                # *.myshopify.com prefix
    export SHOPIFY_ACCESS_TOKEN='shpat_...'       # Admin API token, write_products
    python3 rename_legacy_handles.py --apply

After applying: re-export the store products CSV, replace
products_import_10-27-2026.csv as the LIVE_IMPORT source in
docs/architecture/build_design_registry.py, re-run the builder + asset
generator, and re-push the registry assets. The builder's migration count
must report 0.
"""
import csv
import json
import os
import re
import sys
import urllib.request
import urllib.error
from pathlib import Path

HERE = Path(__file__).resolve().parent          # docs/design/mockups/product imports
MIGRATION = HERE.parents[2] / 'architecture' / 'calder_handle_migration.csv'  # docs/architecture/
SAFE_HANDLE = re.compile(r'^[a-z0-9-]+$')


def api(shop, token, method, path, payload=None):
    url = f'https://{shop}.myshopify.com/admin/api/2024-10/{path}'
    data = None
    headers = {'X-Shopify-Access-Token': token, 'Accept': 'application/json'}
    if payload is not None:
        data = json.dumps(payload).encode()
        headers['Content-Type'] = 'application/json'
    req = urllib.request.Request(url, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=30) as res:
            return res.status, json.loads(res.read() or b'{}')
    except urllib.error.HTTPError as e:
        body = e.read().decode(errors='replace')[:200]
        return e.code, {'error': body}


def main():
    rows = list(csv.DictReader(open(MIGRATION, newline='', encoding='utf-8')))
    if not rows:
        print('No migrations pending — all live handles already match the PN-derived scheme.')
        return

    apply = '--apply' in sys.argv
    shop = os.environ.get('SHOPIFY_SHOP', '')
    token = os.environ.get('SHOPIFY_ACCESS_TOKEN', '')

    bad = [r['pn_derived_handle'] for r in rows if not SAFE_HANDLE.match(r['pn_derived_handle'])]
    if bad:
        sys.exit(f'ABORT: target handles violate the [a-z0-9-] charset: {bad[:3]}')

    print(f'{len(rows)} products to rename. Mode: {"APPLY" if apply else "DRY RUN"}\n')
    done = skipped = failed = 0
    for r in rows:
        current, target = r['current_handle'], r['pn_derived_handle']
        if not apply:
            print(f'  {current}\n    -> {target}')
            continue
        status, body = api(shop, token, 'GET', f'products/{current}.json')
        if status == 404:
            # already renamed (or never existed) — check the target exists
            t_status, _ = api(shop, token, 'GET', f'products/{target}.json')
            if t_status == 200:
                skipped += 1
                print(f'  SKIP (already renamed): {target}')
            else:
                failed += 1
                print(f'  FAIL: neither {current} nor {target} exists')
            continue
        if status != 200:
            failed += 1
            print(f'  FAIL: GET {current} -> HTTP {status} {body.get("error", "")}')
            continue
        pid = body['product']['id']
        status, body = api(shop, token, 'PUT', f'products/{pid}.json',
                           {'product': {'id': pid, 'handle': target}})
        if status == 200:
            done += 1
            print(f'  OK: {current} -> {target}')
        else:
            failed += 1
            print(f'  FAIL: PUT {pid} -> HTTP {status} {body.get("error", "")}')

    if apply:
        print(f'\nRenamed: {done} | Skipped (already done): {skipped} | Failed: {failed}')
        if failed:
            sys.exit(1)
    else:
        print('\nDry run only. Re-run with --apply (and SHOPIFY_SHOP + SHOPIFY_ACCESS_TOKEN set) to execute.')


if __name__ == '__main__':
    main()

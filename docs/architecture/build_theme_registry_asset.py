#!/usr/bin/env python3
"""Generate Shopify theme JS assets from docs/architecture/calder_design_registry.json.

Outputs (theme assets/):
  - calder-design-registry.js              full registry -> window.CALDER_DESIGN_REGISTRY
  - calder-design-registry-{code}.js       per-design slice -> window.CALDER_DESIGN_REGISTRY
                                            (code: clm01, clm02, clm03, clm05, clb06, clb07)

The PDP template should include ONLY its design's slice via a Liquid case on
product.metafields.custom.design_code (documented for Prompt 04 wiring).
Single source of truth remains calder_design_registry.json - regenerate after
any data-sheet revision:
    python3 build_design_registry.py && python3 build_theme_registry_asset.py
"""
import json, gzip
from pathlib import Path

HERE = Path(__file__).resolve().parent
THEME_ASSETS = HERE.parent / 'design' / 'Shopify Themes' / 'Working Theme-via-CLI' / 'assets'
REGISTRY = HERE / 'calder_design_registry.json'


def emit(path, payload):
    js = ('/* GENERATED by docs/architecture/build_theme_registry_asset.py - DO NOT EDIT. */\n'
          '(function (w) { "use strict";\n'
          '  w.CALDER_DESIGN_REGISTRY = ' + payload + ';\n'
          '})(typeof window !== "undefined" ? window : this);\n')
    path.write_text(js)
    raw = len(js)
    gz = len(gzip.compress(js.encode()))
    return raw, gz


def main():
    registry = json.loads(REGISTRY.read_text())
    stats = []
    raw, gz = emit(THEME_ASSETS / 'calder-design-registry.js', json.dumps(registry, separators=(',', ':')))
    stats.append(('calder-design-registry.js (full)', raw, gz))
    for d in registry['designs']:
        slice_obj = dict(registry)
        slice_obj['designs'] = [d]
        name = f"calder-design-registry-{d['legacy_design_code'].lower()}.js"
        raw, gz = emit(THEME_ASSETS / name, json.dumps(slice_obj, separators=(',', ':')))
        stats.append((name, raw, gz))
    for name, raw, gz in stats:
        print(f'{name:44} {raw/1024:7.1f} KB  gzip {gz/1024:6.1f} KB')


if __name__ == '__main__':
    main()
